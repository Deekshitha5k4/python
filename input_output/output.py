name = "Deekshitha"
marks = 85

# 1. Comma-separated print()
print("Name:", name, "Marks:", marks)

# 2. str.format()
print("Name: {}, Marks: {}".format(name, marks))

# 3. f-string
print(f"Name: {name}, Marks: {marks}")
#output:
#Name: Deekshitha Marks: 85
#Name: Deekshitha, Marks: 85
#Name: Deekshitha, Marks: 85
